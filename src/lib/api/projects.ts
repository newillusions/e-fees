// =============================================================================

/**
 * Generates the next sequential project number for a country.
 *
 * Project numbers follow the format YY-CCCNN where:
 * - YY: Two-digit year
 * - CCC: Country dial code
 * - NN: Sequential number
 *
 * @param countryName - Full country name to lookup dial code
 * @param year - Optional year override (defaults to current year)
 * @returns Generated project number (e.g., "25-97105")
 */
export async function generateNextProjectNumber(
  countryName: string,
  year?: number
): Promise<string> {
  try {
    const projectNumber = await invoke<string>('generate_next_project_number', {
      countryName,
      year: year || null
    });
    return projectNumber;
  } catch (error) {
    console.error('Failed to generate project number:', error);
    throw error;
  }
}

/**
 * Validates that a project number is unique and follows correct format.
 * @param projectNumber - Project number to validate (e.g., "25-97105")
 * @returns True if valid and unique, false otherwise
 */
export async function validateProjectNumber(projectNumber: string): Promise<boolean> {
  try {
    const isValid = await invoke<boolean>('validate_project_number', { projectNumber });
    return isValid;
  } catch (error) {
    console.error('Failed to validate project number:', error);
    throw error;
  }
}

