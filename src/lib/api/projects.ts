/**
 * Project API methods
 *
 * Handles all project-related operations including CRUD, pagination,
 * project numbering, and template management.
 */

import { invoke } from '@tauri-apps/api/core';
import type {
  Project,
  ProjectCreate,
  ProjectUpdate,
  PaginatedResponse
} from '../../types';

/**
 * Retrieves all projects from the database.
 * @returns Array of all project records
 */
export async function getProjects(): Promise<Project[]> {
  try {
    const projects = await invoke<Project[]>('get_projects');
    return projects;
  } catch (error) {
    console.error('Failed to fetch projects from database:', error);
    throw error;
  }
}

/**
 * Fetches a paginated page of projects.
 * @param page - Page number (1-indexed)
 * @param pageSize - Number of items per page (default: 50)
 * @returns PaginatedResponse containing projects and metadata
 */
export async function getProjectsPage(
  page: number = 1,
  pageSize: number = 50
): Promise<PaginatedResponse<Project>> {
  try {
    const response = await invoke<PaginatedResponse<Project>>('get_projects_page', {
      page,
      pageSize
    });
    return response;
  } catch (error) {
    console.error('Failed to fetch projects page:', error);
    throw error;
  }
}

/**
 * Fetches a single project by ID.
 * @param id - Project ID
 * @returns Project or null if not found
 */
export async function getProjectById(id: string): Promise<Project | null> {
  try {
    const project = await invoke<Project | null>('get_project_by_id', { id });
    return project;
  } catch (error) {
    console.error('Failed to fetch project by ID:', error);
    throw error;
  }
}

/**
 * Searches projects by name, location, or project number.
 * @param query - Search term to match against project fields
 * @returns Array of matching project records
 */
export async function searchProjects(query: string): Promise<Project[]> {
  try {
    const projects = await invoke<Project[]>('search_projects', { query });
    return projects;
  } catch (error) {
    console.error('Failed to search projects:', error);
    throw error;
  }
}

/**
 * Creates a new project record in the database.
 * @param project - Project data without ID (will be generated by database)
 * @returns Created project or null on failure
 */
export async function createProject(project: ProjectCreate): Promise<Project | null> {
  try {
    const newProject = {
      ...project,
      id: null,
      time: {
        created_at: new Date().toISOString(),
        updated_at: new Date().toISOString()
      }
    };

    const created = await invoke<Project>('create_project', { project: newProject });
    return created;
  } catch (error) {
    console.error('Failed to create project:', error);
    return null;
  }
}

/**
 * Updates an existing project record.
 * @param id - Project ID
 * @param projectData - Updated project data
 * @returns Updated project
 */
export async function updateProject(id: string, projectData: ProjectUpdate): Promise<Project> {
  try {
    const updated = await invoke<Project>('update_project', { id, projectUpdate: projectData });
    return updated;
  } catch (error) {
    console.error('Failed to update project:', error);
    throw error;
  }
}

/**
 * Deletes a project record from the database.
 * @param id - Project ID
 * @returns Deleted project data
 */
export async function deleteProject(id: string): Promise<Project> {
  try {
    const deleted = await invoke<Project>('delete_project', { id });
    return deleted;
  } catch (error) {
    console.error('Failed to delete project:', error);
    throw error;
  }
}

