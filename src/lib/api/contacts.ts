/**
 * Contact API methods
 *
 * Handles all contact-related operations including CRUD and pagination.
 */

import { invoke } from '@tauri-apps/api/core';
import type { Contact, ContactCreate, ContactUpdate, PaginatedResponse } from '../../types';
import { logApiError } from '../services/logger';

/**
 * Retrieves all contacts from the database with company information.
 * @returns Array of all contact records with company data
 */
export async function getContacts(): Promise<Contact[]> {
  try {
    const contacts = await invoke<Contact[]>('get_contacts');
    return contacts;
  } catch (error) {
    logApiError('getContacts', error as Error, { component: 'ContactsApi' });
    throw error;
  }
}

/**
 * Fetches a paginated page of contacts.
 * @param page - Page number (1-indexed)
 * @param pageSize - Number of items per page (default: 50)
 * @returns PaginatedResponse containing contacts and metadata
 */
export async function getContactsPage(
  page: number = 1,
  pageSize: number = 50
): Promise<PaginatedResponse<Contact>> {
  try {
    const response = await invoke<PaginatedResponse<Contact>>('get_contacts_page', {
      page,
      pageSize
    });
    return response;
  } catch (error) {
    logApiError('getContactsPage', error as Error, { component: 'ContactsApi' });
    throw error;
  }
}

/**
 * Fetches a single contact by ID.
 * @param id - Contact ID
 * @returns Contact or null if not found
 */
export async function getContactById(id: string): Promise<Contact | null> {
  try {
    const contact = await invoke<Contact | null>('get_contact_by_id', { id });
    return contact;
  } catch (error) {
    logApiError('getContactById', error as Error, { component: 'ContactsApi' });
    throw error;
  }
}

/**
 * Creates a new contact record in the database.
 * @param contact - Contact data without ID (will be generated by database)
 * @returns Created contact
 * @throws Error if creation fails
 */
export async function createContact(contact: ContactCreate): Promise<Contact> {
  try {
    const newContact = {
      ...contact,
      id: null
    };

    const created = await invoke<Contact>('create_contact', { contact: newContact });
    return created;
  } catch (error) {
    logApiError('createContact', error as Error, { component: 'ContactsApi' });
    throw error;
  }
}

/**
 * Updates an existing contact with partial data.
 * @param id - Contact ID (string, extracted from SurrealDB Thing object)
 * @param contactUpdate - Partial contact data - only fields to update
 * @returns Updated contact
 * @throws Error if update fails
 */
export async function updateContact(
  id: string,
  contactUpdate: ContactUpdate
): Promise<Contact> {
  try {
    const updated = await invoke<Contact>('update_contact', {
      id,
      contactUpdate
    });
    return updated;
  } catch (error) {
    logApiError('updateContact', error as Error, { component: 'ContactsApi' });
    throw error;
  }
}

/**
 * Deletes a contact from the database.
 * @param id - Contact ID (string, extracted from SurrealDB Thing object)
 * @returns Deleted contact
 * @throws Error if deletion fails
 */
export async function deleteContact(id: string): Promise<Contact> {
  try {
    const deleted = await invoke<Contact>('delete_contact', { id });
    return deleted;
  } catch (error) {
    logApiError('deleteContact', error as Error, { component: 'ContactsApi' });
    throw error;
  }
}
